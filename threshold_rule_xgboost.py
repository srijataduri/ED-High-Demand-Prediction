test_df = probs[probs["split"] == "test"].copy()

y_val = val_df["y_true"].to_numpy()
y_test = test_df["y_true"].to_numpy()

# 2. Tune probability cutoff per model using ONLY validation rows
tuned_cutoffs = {}
tuning_summary = []

for col in prob_cols:
    val_scores = val_df[col].to_numpy()
    precisions, recalls, thresholds = precision_recall_curve(y_val, val_scores)

    p = precisions[:-1]
    r = recalls[:-1]

    denom = p + r
    f1_scores = np.zeros_like(denom, dtype=float)

    np.divide(
      2 * p * r,
      denom,
      out=f1_scores,
      where=denom > 0
    )
    best_idx = int(np.argmax(f1_scores))
    best_cutoff = float(thresholds[best_idx])

    model_name = MODEL_NAME_MAP[col]
    tuned_cutoffs[model_name] = round(best_cutoff, 6)

    val_pred = (val_scores >= best_cutoff).astype(int)
    test_scores = test_df[col].to_numpy()
    test_pred = (test_scores >= best_cutoff).astype(int)

    tuning_summary.append({
        "model": model_name,
        "cutoff": round(best_cutoff, 4),
        "val_pr_auc": round(average_precision_score(y_val, val_scores), 3),
        "val_f1": round(f1_score(y_val, val_pred, zero_division=0), 3),
        "test_pr_auc": round(average_precision_score(y_test, test_scores), 3),
        "test_recall": round(recall_score(y_test, test_pred, zero_division=0), 3),
        "test_precision": round(precision_score(y_test, test_pred, zero_division=0), 3),
        "test_f1": round(f1_score(y_test, test_pred, zero_division=0), 3),
    })

