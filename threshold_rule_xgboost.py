"""## 4. Features (D3)

All features describing hour *t* use only information available **before** hour *t* (lags / rolling windows on past hours) or known in advance (calendar). The target is whether hour *t* is a high-demand hour, i.e., a one-hour-ahead alert.

Rolling windows require a complete window (`min_periods = window`), so they are NaN within one window after a missing day. Tree models can use NaN directly; for LR / KNN / SVM, either drop rows with `has_all_features == 0` or impute inside the model pipeline (fit on training data only).
"""

def make_features(v2_df, holidays=None):
    v2_df = v2_df.copy()
    dt, y = v2_df["datetime"], v2_df["arrivals"]

    # Calendar (known in advance)
    v2_df["hour"] = dt.dt.hour
    v2_df["day_of_week"] = dt.dt.dayofweek
    v2_df["month"] = dt.dt.month
    v2_df["is_weekend"] = (v2_df["day_of_week"] >= 5).astype(int)
    v2_df["is_holiday"] = dt.dt.normalize().isin(holidays).astype(int) if holidays is not None else 0
    for col, period in [("hour", 24), ("day_of_week", 7), ("month", 12)]:
        v2_df[f"{col}_sin"] = np.sin(2 * np.pi * v2_df[col] / period)
        v2_df[f"{col}_cos"] = np.cos(2 * np.pi * v2_df[col] / period)

    # Lags (exact offsets on the complete hourly grid)
    for k in (1, 2, 3, 24, 168):
        v2_df[f"lag_{k}"] = y.shift(k)

    # Rolling statistics on past hours only
    past = y.shift(1)
    for w in (3, 6, 24):
        v2_df[f"rolling_mean_{w}"] = past.rolling(w, min_periods=w).mean()
    v2_df["rolling_std_24"] = past.rolling(24, min_periods=24).std()
    v2_df["rolling_max_24"] = past.rolling(24, min_periods=24).max()

    # Same hour over the previous 7 days (needs at least 4 of 7 observed)
    same_hour = pd.concat([y.shift(24 * d) for d in range(1, 8)], axis=1)
    v2_df["same_hour_mean_7d"] = same_hour.mean(axis=1).where(same_hour.notna().sum(axis=1) >= 4)
    return v2_df

holidays = USFederalHolidayCalendar().holidays(start=hourly["datetime"].min(), end=hourly["datetime"].max())
