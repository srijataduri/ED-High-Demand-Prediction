def best_f1_cutoff(y, score):
    p, r, t = precision_recall_curve(y, score)
    f = 2 * p[:-1] * r[:-1] / np.clip(p[:-1] + r[:-1], 1e-12, None)
    return t[np.nanargmax(f)]

def record(name, score_va, score_te, pred_va=None, pred_te=None, default_cutoff=0.5):
    # Logs metrics at the default cutoff (or the rule's own prediction) and at a validation-tuned cutoff.
    score_va, score_te = np.asarray(score_va, float), np.asarray(score_te, float)
    tuned = best_f1_cutoff(y_va, score_va)
    for split, y, s, p in (("validation", y_va, score_va, pred_va), ("test", y_te, score_te, pred_te)):
        p_default = (s >= default_cutoff).astype(int) if p is None else np.asarray(p, int)
        RESULTS.append({"model": name, "split": split, "cutoff": "default", "cutoff_value": default_cutoff if p is None else np.nan,
                        **evaluate(y, s, p_default)})
        RESULTS.append({"model": name, "split": split, "cutoff": "val-tuned (prelim.)", "cutoff_value": tuned,
                        **evaluate(y, s, (s >= tuned).astype(int))})
        PRED[split][f"score_{name}"] = s
    SCORES[name] = (score_va, score_te)
    row = pd.DataFrame(RESULTS)
    show = row[(row["model"] == name)].set_index(["split", "cutoff"])
    return show[["recall", "precision", "f1", "pr_auc", "alerts_per_day"]].round(3)

def tune(name, estimator, grid, X, y, n_iter=None):
    t0 = time.time()
    Search = RandomizedSearchCV if n_iter else GridSearchCV
    kw = {"n_iter": n_iter, "random_state": RANDOM_STATE} if n_iter else {}
    search = Search(estimator, grid, scoring="average_precision", cv=tscv, n_jobs=-1, refit=True, **kw)
    search.fit(X, y)
    BEST_PARAMS[name] = {k: (v.item() if hasattr(v, "item") else v) for k, v in search.best_params_.items()}
    print(f"{name}: best CV PR-AUC = {search.best_score_:.3f} | {BEST_PARAMS[name]} | {time.time() - t0:.0f}s")
    return search.best_estimator_

