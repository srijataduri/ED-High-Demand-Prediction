def v1_original(long):
    v2_df = long[["datetime"]].copy()
    v2_df["arrivals"] = long["value"].fillna(0)
    return v2_df.sort_values("datetime").reset_index(drop=True)

def v1_corrected(long, grid):
    v2_df = long.set_index("datetime")[["value"]].rename(columns={"value": "arrivals"})
    return v2_df.reindex(grid).rename_axis("datetime").reset_index()

