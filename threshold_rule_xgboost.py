def parse_date_label(v):
    # Returns (month, day) for a date column, None for totals / non-date columns.
    if pd.isna(v):
        return None
    if isinstance(v, (pd.Timestamp, datetime)):
        return (v.month, v.day)
    s = str(v).strip()
    if "Total" in s:
        return None
    m = re.fullmatch(r"(\d{1,2})-([A-Za-z]{3})", s)
    if not m:
        return None
    return (datetime.strptime(m.group(2).title(), "%b").month, int(m.group(1)))

def parse_year(v):
    try:
        f = float(str(v).strip())
    except ValueError:
        return None
    return int(f) if f.is_integer() and 1900 <= f <= 2100 else None

