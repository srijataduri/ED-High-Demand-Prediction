def best_f1_cutoff(y_true, scores):

    precision, recall, thresholds = precision_recall_curve(
        y_true,
        scores
    )

    p = precision[:-1]
    r = recall[:-1]

    denominator = p + r

    f1_values = np.zeros_like(
        denominator,
        dtype=float
    )

    np.divide(
        2 * p * r,
        denominator,
        out=f1_values,
        where=denominator > 0
    )

    best_idx = int(np.argmax(f1_values))

    return float(thresholds[best_idx])


